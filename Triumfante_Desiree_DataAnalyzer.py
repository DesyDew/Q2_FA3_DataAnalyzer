# STUDENT SCORE ANALYZER

# Numeric dataset
scores = [85, 90, 78, 92, 88, 76, 95, 83, 89, 80]

# 1. Display Scores
def display_scores():
  print("\n===== STUDENT SCORES =====")
  print(scores)

# 2. Search Score
def search_score():
  number = int(input("Enter score to search: "))

  if number in scores:
    print("Score found!")
  else:
    print("Score not found.")

# 3. Compute Average
def compute_average():
  average = sum(scores) / len(scores)
  print("Average Score:", round(average, 2))

# 4. Update Score
def update_score():
  index = int(input("Enter student number (1-10): ")) - 1

  if 0 <= index < len(scores):
    new_score = int(input("Enter new score: "))

    if 0 <= new_score <= 100:
      scores[index] = new_score
      print("Score updated!")
    else:
      print("Invalid score.")
  else:
    print("Invalid student number.")

# 5. Display Updated Scores
def display_updated_scores():
  print("\n===== UPDATED SCORES =====")
  print(scores)

# Main Menu
def main():
  while True:
    print("\n===== STUDENT SCORE ANALYZER =====")
    print("1. Display Scores")
    print("2. Search Score")
    print("3. Compute Average")
    print("4. Update Score")
    print("5. Display Updated Scores")
    print("6. Exit")

    choice = input("Enter your choice: ")

    if choice == "1":
      display_scores()
    elif choice == "2":
      search_score()
    elif choice == "3":
      compute_average()
    elif choice == "4":
      update_score()
    elif choice == "5":
      display_updated_scores()
    elif choice == "6":
      print("Thank your for using the analyzer!")
      break
    else:
      print("Invalid choice.")

main()